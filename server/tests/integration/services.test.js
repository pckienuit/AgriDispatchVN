import assert from 'node:assert/strict';
import { once } from 'node:events';
import { test } from 'node:test';
import { createAccountApp } from '../../src/account-app.js';
import { createApp } from '../../src/app.js';
import { createPool } from '../../src/db.js';
import { migrate } from '../../scripts/migrate.js';
import { seedCatalog } from '../../scripts/seed-catalog.js';
import { createDisposableDatabase } from '../helpers/test-db.js';

const secret = 'integration-service-credential-0123456789abcdef';

test('combined migrations and catalog use real account HTTP identity, then fail closed on outage', async (t) => {
  const db = await createDisposableDatabase(process.env.TEST_DATABASE_URL);
  const pool = createPool(db.url);
  const servers = [];
  t.after(async () => {
    for (const server of servers) {
      if (server.listening) await new Promise((resolve) => { server.close(resolve); server.closeAllConnections(); });
    }
    await pool.end();
    await db.drop();
  });
  const applied = await migrate(pool);
  assert.ok(applied.includes('001_accounts.sql'));
  assert.ok(applied.includes('002_catalog.sql'));
  assert.deepEqual(await migrate(pool), []);
  await seedCatalog(pool);
  const listen = async (app) => {
    const server = app.listen(0, '127.0.0.1');
    servers.push(server);
    await once(server, 'listening');
    return { server, url: `http://127.0.0.1:${server.address().port}` };
  };
  const account = await listen(createAccountApp({ pool, internalServiceToken: secret }));
  const booking = await listen(createApp({ pool, accountServiceUrl: account.url, internalServiceToken: secret }));
  const post = (url, path, body, token) => fetch(url + path, {
    method: 'POST', headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    body: JSON.stringify(body),
  });
  const input = { email: 'integration@example.com', name: 'Synthetic Farmer', password: 'integration-only-passphrase' };
  assert.equal((await post(account.url, '/api/auth/register', input)).status, 201);
  const login = await post(account.url, '/api/auth/login', { email: input.email, password: input.password });
  const session = await login.json();
  const services = await fetch(booking.url + '/api/services');
  assert.equal(services.status, 200);
  assert.equal((await services.json()).items.length, 3);
  const fieldResponse = await post(booking.url, '/api/fields', { name: 'Ruộng demo', locality: 'Địa bàn mô phỏng', areaM2: 12000 }, session.token);
  assert.equal(fieldResponse.status, 201);
  const { field } = await fieldResponse.json();
  const request = { fieldId: field.id, serviceId: '00000000-0000-4000-8000-000000000102', startAt: '2026-11-25T08:00:00Z', endAt: '2026-11-25T12:00:00Z' };
  const createOrder = (token = session.token) => fetch(booking.url + '/api/bookings', {
    method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}`, 'Idempotency-Key': 'live-http-booking-key-0001' }, body: JSON.stringify(request),
  });
  const order = await createOrder();
  assert.equal(order.status, 201);
  const original = await order.json();
  assert.deepEqual(await (await createOrder()).json(), original);
  assert.equal(original.booking.totalVnd, '1440000');
  const mine = await fetch(booking.url + '/api/fields', { headers: { Authorization: `Bearer ${session.token}` } });
  assert.equal((await mine.json()).items.length, 1);
  const gatewayLogin = await post(booking.url, '/api/auth/login', { email: input.email, password: input.password });
  assert.equal(gatewayLogin.status, 200);
  const gatewaySession = await gatewayLogin.json();
  assert.equal((await fetch(booking.url + '/api/me', { headers: { Authorization: `Bearer ${gatewaySession.token}` } })).status, 200);
  assert.equal((await post(booking.url, '/api/machines', { name: 'Máy demo', type: 'harvester' }, session.token)).status, 403);
  const other = { ...input, email: 'other-integration@example.com' };
  assert.equal((await post(account.url, '/api/auth/register', other)).status, 201);
  const second = await (await post(account.url, '/api/auth/login', { email: other.email, password: other.password })).json();
  const theirs = await fetch(booking.url + '/api/fields', { headers: { Authorization: `Bearer ${second.token}` } });
  assert.deepEqual((await theirs.json()).items, []);
  const coopAccount = await post(booking.url, '/api/auth/register', { email: 'synthetic-coop@example.com', password: input.password, name: 'HTX mô phỏng' });
  assert.equal(coopAccount.status, 201);
  const coopId = (await coopAccount.json()).user.id;
  await pool.query("INSERT INTO account.user_roles(user_id,role) VALUES($1,'coop')", [coopId]);
  const coopSession = await (await post(booking.url, '/api/auth/login', { email: 'synthetic-coop@example.com', password: input.password })).json();
  const coordinatorRead = (path, token) => fetch(booking.url + path, { headers: { Authorization: 'Bearer ' + token } });
  const directory = await coordinatorRead('/api/coordinators', session.token);
  assert.equal(directory.status, 200);
  assert.deepEqual((await directory.json()).items, [{ id:coopId, name:'HTX mô phỏng' }]);
  const assignmentPath = `/api/bookings/${original.booking.id}/coordinator`;
  const beforeAssignment = await (await coordinatorRead(assignmentPath, session.token)).json();
  assert.equal(beforeAssignment.coordinatorId, null);
  assert.equal(beforeAssignment.canAssign, true);
  assert.equal((await coordinatorRead(assignmentPath, second.token)).status, 404);
  assert.equal((await post(booking.url, `/api/bookings/${original.booking.id}/coordinator`, { coordinatorId: coopId }, session.token)).status, 200);
  const scopedRead = (path, token) => fetch(booking.url + path, { headers: { Authorization: 'Bearer ' + token } });
  const delegated = await scopedRead('/api/dispatch/bookings', coopSession.token);
  assert.equal(delegated.status, 200);
  assert.deepEqual((await delegated.json()).items.map((item) => item.id), [original.booking.id]);
  assert.equal((await scopedRead('/api/dispatch/bookings', session.token)).status, 403);
  const grouped = await post(booking.url, '/api/packages', { bookingIds: [original.booking.id] }, coopSession.token);
  assert.equal(grouped.status, 201);
  assert.equal((await (await coordinatorRead(assignmentPath, session.token)).json()).canAssign, false);
  const packageId = (await grouped.json()).package.id;
  const createRole = async (label, role) => {
    const email = `synthetic-${label}@example.com`;
    const reg = await post(booking.url, '/api/auth/register', { email, password: input.password, name: `Synthetic ${label}` });
    assert.equal(reg.status, 201);
    const user = (await reg.json()).user;
    await pool.query('INSERT INTO account.user_roles(user_id,role) VALUES($1,$2)', [user.id, role]);
    const auth = await (await post(booking.url, '/api/auth/login', { email, password: input.password })).json();
    return { id: user.id, token: auth.token };
  };
  const provider = await createRole('provider', 'provider');
  const operator = await createRole('operator', 'operator');
  const job = await post(booking.url, '/api/jobs', { title: 'Synthetic shift', locality: 'Synthetic', capacity: 1, startAt: request.startAt, endAt: request.endAt }, provider.token);
  assert.equal(job.status, 201);
  const jobId = (await job.json()).job.id;
  const application = await post(booking.url, `/api/jobs/${jobId}/applications`, {}, operator.token);
  const applicationId = (await application.json()).application.id;
  const offer = await post(booking.url, `/api/applications/${applicationId}/offers`, {}, provider.token);
  const offerId = (await offer.json()).offer.id;
  assert.equal((await post(booking.url, `/api/offers/${offerId}/accept`, {}, operator.token)).status, 200);
  const acceptedOperators = await scopedRead('/api/dispatch/operators', provider.token);
  assert.equal(acceptedOperators.status, 200);
  assert.equal((await acceptedOperators.json()).items[0].id, operator.id);
  assert.deepEqual((await (await scopedRead('/api/dispatch/bookings', coopSession.token)).json()).items, []);
  const machine = await post(booking.url, '/api/machines', { name: 'Synthetic harvester', type: 'harvester' }, provider.token);
  const machineId = (await machine.json()).machine.id;
  assert.equal((await post(booking.url, `/api/packages/${packageId}/claim`, { machineId, operatorId: operator.id }, provider.token)).status, 200);
  const readAs = (path, token) => fetch(booking.url + path, { headers: { Authorization: `Bearer ${token}` } });
  const pendingShift = await readAs('/api/shift-packages', operator.token);
  assert.equal(pendingShift.status, 200);
  const pendingPackages = (await pendingShift.json()).packages;
  assert.equal(pendingPackages[0].id, packageId);
  assert.equal(pendingPackages[0].ready, false);
  assert.equal((await readAs('/api/shift-packages', provider.token)).status, 403);
  assert.equal((await readAs('/api/shift-packages?limit=101', operator.token)).status, 400);
  const outsider = await createRole('outside-operator', 'operator');
  assert.deepEqual((await (await readAs('/api/shift-packages', outsider.token)).json()).packages, []);
  assert.equal((await post(booking.url, `/api/bookings/${original.booking.id}/readiness`, { drained: true, mature: true, intakeReady: true }, session.token)).status, 200);
  assert.equal((await (await readAs('/api/shift-packages', operator.token)).json()).packages[0].ready, true);
  const started = await post(booking.url, `/api/packages/${packageId}/shifts/start`, {}, operator.token);
  assert.equal(started.status, 201);
  const shiftId = (await started.json()).shift.id;
  assert.equal((await (await readAs(`/api/bookings/${original.booking.id}/acceptance`, provider.token)).json()).permissions.canPropose, false);
  assert.equal((await (await readAs(`/api/shifts/${shiftId}`, operator.token)).json()).shift.canOperate, true);
  assert.equal((await (await readAs(`/api/shifts/${shiftId}`, provider.token)).json()).shift.canOperate, false);
  assert.deepEqual((await (await readAs('/api/shift-packages', operator.token)).json()).packages, []);
  assert.equal((await post(booking.url, `/api/shifts/${shiftId}/pause`, { reason: 'Synthetic rain' }, operator.token)).status, 200);
  assert.equal((await post(booking.url, `/api/shifts/${shiftId}/resume`, {}, operator.token)).status, 200);
  assert.equal((await post(booking.url, `/api/shifts/${shiftId}/complete`, { areaM2: 12000 }, operator.token)).status, 200);
  const acceptanceReadPath = `/api/bookings/${original.booking.id}/acceptance`;
  assert.deepEqual((await (await readAs(acceptanceReadPath, provider.token)).json()).permissions, {party:'provider',canPropose:true,blockedByDispute:false});
  assert.equal((await (await readAs(acceptanceReadPath, session.token)).json()).permissions.party, 'owner');
  assert.equal((await (await readAs(acceptanceReadPath, coopSession.token)).json()).permissions.party, null);
  const acceptancePath = `/api/bookings/${original.booking.id}/acceptance`;
  assert.equal((await post(booking.url, acceptancePath, { areaM2: 12000, totalVnd: original.booking.totalVnd }, provider.token)).status, 201);
  assert.equal((await post(booking.url, `${acceptancePath}/1/consent`, {}, coopSession.token)).status, 404);
  assert.equal((await post(booking.url, `${acceptancePath}/1/consent`, {}, session.token)).status, 200);
  assert.equal((await post(booking.url, `${acceptancePath}/1/consent`, {}, provider.token)).status, 200);
  const reported = await post(booking.url, `/api/bookings/${original.booking.id}/payments`, { amountVnd: original.booking.totalVnd, reference: 'SYNTHETIC-HTTP-TRANSFER' }, session.token);
  assert.equal(reported.status, 201);
  const claim = await reported.json();
  assert.equal(claim.payment.status, 'REPORTED');
  assert.equal(claim.summary.outstandingVnd, original.booking.totalVnd);
  const confirmed = await post(booking.url, `/api/payments/${claim.payment.id}/confirm`, {}, provider.token);
  assert.equal(confirmed.status, 200);
  assert.equal((await confirmed.json()).summary.outstandingVnd, '0');
  assert.equal((await (await readAs(acceptanceReadPath, provider.token)).json()).permissions.canPropose, false);
  const opened = await post(booking.url, `/api/bookings/${original.booking.id}/disputes`, { reason: 'QUALITY', details: 'Synthetic quality claim' }, session.token);
  assert.equal(opened.status, 201);
  const disputeId = (await opened.json()).dispute.id;
  assert.equal((await (await readAs(acceptanceReadPath, provider.token)).json()).permissions.blockedByDispute, true);
  assert.equal((await post(booking.url, `/api/disputes/${disputeId}/responses`, { text: 'Synthetic provider response' }, provider.token)).status, 201);
  const frozen = await post(booking.url, `${acceptancePath}/1/consent`, {}, session.token);
  assert.equal(frozen.status, 409);
  assert.equal((await frozen.json()).error.code, 'DISPUTE_OPEN');
  const mediator = await createRole('mediator', 'admin');
  const reviewQueue = await readAs('/api/dispute-review', mediator.token);
  assert.equal(reviewQueue.status, 200);
  assert.equal((await readAs('/api/dispute-review?limit=101', mediator.token)).status, 400);
  assert.ok((await reviewQueue.json()).items.some(item => item.id===disputeId));
  assert.equal((await readAs(`/api/disputes/${disputeId}`, mediator.token)).status, 200);
  assert.equal((await readAs(`/api/disputes/${disputeId}/proposals`, mediator.token)).status, 200);
  const candidates = await readAs(`/api/dispute-review/${disputeId}/mediators`, mediator.token);
  assert.equal(candidates.status, 200);
  assert.equal((await readAs(`/api/dispute-review/${disputeId}/mediators?offset=10001`, mediator.token)).status, 400);
  assert.deepEqual((await candidates.json()).items.map(item=>item.id), [mediator.id]);
  assert.equal((await readAs('/api/dispute-review', provider.token)).status, 403);
  await pool.query("INSERT INTO account.user_roles(user_id,role) VALUES($1,'admin')", [coopId]);
  const involvedAuth = await (await post(booking.url, '/api/auth/login', {email:'synthetic-coop@example.com',password:input.password})).json();
  assert.ok(!(await (await readAs('/api/dispute-review', involvedAuth.token)).json()).items.some(item=>item.id===disputeId));
  assert.equal((await readAs(`/api/disputes/${disputeId}`, involvedAuth.token)).status, 404);
  assert.equal((await readAs(`/api/dispute-review/${disputeId}/mediators`, involvedAuth.token)).status, 404);
  assert.equal((await post(booking.url, `/api/disputes/${disputeId}/mediator`, { mediatorId: mediator.id }, mediator.token)).status, 200);
  assert.equal((await post(booking.url, `/api/disputes/${disputeId}/proposals`, { text: 'Synthetic mutually accepted remedy, no money executed' }, mediator.token)).status, 201);
  assert.equal((await post(booking.url, `/api/disputes/${disputeId}/proposals/1/consent`, {}, session.token)).status, 200);
  const resolution = await post(booking.url, `/api/disputes/${disputeId}/proposals/1/consent`, {}, provider.token);
  assert.equal(resolution.status, 200);
  assert.equal((await resolution.json()).dispute.status, 'RESOLVED');
  const activity = await readAs('/api/activity?limit=100', session.token);
  assert.equal(activity.status, 200);
  const feed = (await activity.json()).items;
  assert.ok(feed.some(item=>item.type==='booking.BOOKING_REQUESTED' && item.href===`#booking/${original.booking.id}`));
  assert.ok(feed.some(item=>item.type==='remedy.RESOLVED' && item.href===`#dispute/${disputeId}`));
  assert.deepEqual((await (await readAs('/api/activity', second.token)).json()).items, []);
  assert.equal((await fetch(booking.url+'/api/activity')).status, 401);
  assert.ok(!(await (await readAs('/api/dispute-review', mediator.token)).json()).items.some(item=>item.id===disputeId));
  assert.equal((await post(booking.url, `/api/packages/${packageId}/cancel`, { reason: 'Cannot erase work' }, coopSession.token)).status, 409);
  assert.equal((await pool.query('SELECT count(*)::int n FROM dispatch.allocations WHERE package_id=$1 AND released_at IS NULL', [packageId])).rows[0].n, 2);
  assert.equal((await post(booking.url, '/api/packages', { bookingIds: [original.booking.id] }, session.token)).status, 403);
  await new Promise((resolve) => { account.server.close(resolve); account.server.closeAllConnections(); });
  const failed = await post(booking.url, '/api/fields', { name: 'Không lưu', locality: 'Demo', areaM2: 1000 }, session.token);
  assert.equal(failed.status, 503);
  assert.equal((await pool.query('SELECT count(*)::integer AS n FROM dispatch.fields')).rows[0].n, 1);
});
